def update_readme() -> bool:
    readme = paths.REPO / "README.md"
    if not readme.exists():
        return False
    text = readme.read_text(encoding="utf-8")
    begin, end = "<!-- BEGIN GENERATED headline (python -m mlipft docs) -->", "<!-- END GENERATED headline -->"
    if begin not in text:
        return False
    start, stop = text.index(begin) + len(begin), text.index(end)
    readme.write_text(text[:start] + "\n" + readme_headline() + "\n" + text[stop:], encoding="utf-8")
    return True


def build() -> list[str]:
    written = []
    for name, maker in (("results.md", results_markdown), ("reproduction.md", reproduction_markdown),
                        ("figures.md", figures_markdown)):
        try:
            (paths.DOCS / name).write_text(maker(), encoding="utf-8")
            written.append(f"docs/{name}")
        except (FileNotFoundError, ModuleNotFoundError) as error:
            print(f"skipped docs/{name}: {error}")
    if update_readme():
        written.append("README.md (headline tables)")
    return written
