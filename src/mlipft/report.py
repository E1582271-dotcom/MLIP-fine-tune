def _read(name: str) -> pd.DataFrame:
    return pd.read_csv(paths.RESULTS / name, keep_default_na=False, na_values=[""], float_precision="round_trip")


def num(value, digits: int = 3) -> str:
    """``digits`` significant figures; scientific notation only below 1e-3 or from 1e5."""
    if value is None or value == "" or (isinstance(value, float) and math.isnan(value)):
        return "-"
    value = float(value)
    if value == 0:
        return "0"
    if abs(value) >= 1e5 or abs(value) < 1e-3:
        return f"{value:.{digits - 1}e}".replace("e-0", "e-").replace("e+0", "e")
    rounded = float(f"{value:.{digits}g}")
    decimals = max(digits - 1 - math.floor(math.log10(abs(rounded))), 0)
    return f"{rounded:.{decimals}f}"


def sigma_text(row) -> str:
    return f"{num(row['sigma300_mS_cm'])} [{num(row['sigma300_min_mS_cm'], 2)}, {num(row['sigma300_max_mS_cm'], 2)}]"


def ea_text(row) -> str:
    return f"{row['Ea_eV']:.3f} ± {row['Ea_err_eV']:.3f}"


def table(header, rows) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def quoted_fits() -> pd.DataFrame:
    fits = _read("fits.csv")
    return fits[fits["quoted"].astype(str).str.lower() == "true"].set_index("series")


